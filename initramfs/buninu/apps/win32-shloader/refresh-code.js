// Maintainer-only: refresh the checked-in instruction templates after editing .S.
// Normal PE generation uses index.js and needs no compiler.
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const here = dirname(fileURLToPath(import.meta.url));
const temporary = mkdtempSync(join(tmpdir(), 'buninu-shloader-asm-'));
const stringAt = (buffer, pos) => buffer.toString('utf8', pos, buffer.indexOf(0, pos));
try {
  const templates = {};
  for (const [arch, target, machine] of [['x64', 'x86_64-linux-gnu', 62], ['arm64', 'aarch64-linux-gnu', 183]]) {
    const source = join(here, arch + '.S'), object = join(temporary, arch + '.o');
    const result = spawnSync('clang', ['--target=' + target, '-c', source, '-o', object], { stdio: 'inherit' });
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error('Assembly failed: ' + arch);
    const elf = readFileSync(object);
    if (elf.toString('hex', 0, 6) !== '7f454c460201' || elf.readUInt16LE(18) !== machine)
      throw new Error('Expected a little-endian ELF64 object');
    const table = Number(elf.readBigUInt64LE(40)), width = elf.readUInt16LE(58), count = elf.readUInt16LE(60);
    const sections = Array.from({ length: count }, (_, i) => {
      const p = table + width * i;
      return { nameOffset: elf.readUInt32LE(p), offset: Number(elf.readBigUInt64LE(p + 24)),
        size: Number(elf.readBigUInt64LE(p + 32)), link: elf.readUInt32LE(p + 40), stride: Number(elf.readBigUInt64LE(p + 56)) };
    });
    const names = sections[elf.readUInt16LE(62)];
    sections.forEach(s => s.name = stringAt(elf, names.offset + s.nameOffset));
    const code = sections.find(s => s.name === '.text'), rela = sections.find(s => s.name === '.rela.text');
    const symbols = sections[rela.link], strings = sections[symbols.link];
    const relocations = [];
    for (let p = rela.offset; p < rela.offset + rela.size; p += rela.stride) {
      const info = elf.readBigUInt64LE(p + 8), symbol = symbols.offset + Number(info >> 32n) * symbols.stride;
      const name = stringAt(elf, strings.offset + elf.readUInt32LE(symbol));
      if (elf.readUInt16LE(symbol + 6) !== 0) throw new Error('Unexpected non-external relocation: ' + name);
      relocations.push([Number(elf.readBigUInt64LE(p)), Number(info & 0xffffffffn), name, Number(elf.readBigInt64LE(p + 16))]);
    }
    templates[arch] = { sourceSHA256: createHash('sha256').update(readFileSync(source)).digest('hex'),
      code: elf.subarray(code.offset, code.offset + code.size).toString('base64'), relocations };
  }
  writeFileSync(join(here, 'code.js'), '// Generated by refresh-code.js; source is x64.S / arm64.S. No compiler needed to use.\n' +
    'export const nativeCode = ' + JSON.stringify(templates, null, 2) + ';\n');
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
